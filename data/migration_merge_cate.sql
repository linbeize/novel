-- ============================================================
-- 分类合并迁移：把「源站无法映射」的冷门分类并入「其他类型」
--
-- 背景：本地分类表沿用了 12 个分类，但采集源（5566xs）只有 8 个分类，
-- 规则 cate_maps 只能映射到 8 个本地 id。以下 4 个分类永远收不到书：
--     5  侦探推理
--     8  恐怖灵异
--     10 架空历史
--     12 同人耽美
-- 它们只是让导航栏多占 4 个位置（导航从 14 项降到 10 项）。
--
-- 处理方式：
--     1) 先把可能挂在这 4 个分类下的小说改挂到「其他类型」(id=13)
--     2) 再对这 4 个分类做软删除（deleted_at），数据保留、可恢复
--
-- 特性：幂等，可重复执行；执行前自动备份到 nov_cate_bak_merge
-- 执行：mysql -unovel -p'novel@2024' -h127.0.0.1 -P3307 gonovel < migration_merge_cate.sql
-- ============================================================

USE gonovel;

-- ------------------------------------------------------------
-- 1. 备份（仅首次执行时创建，避免重复执行覆盖原始备份）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS nov_cate_bak_merge AS
SELECT * FROM nov_cate;

-- ------------------------------------------------------------
-- 2. 把冷门分类下的小说改挂到「其他类型」(13)
--    cate_id 与 cate_name 在本程序中是双写的，两者都要更新
--    当前这 4 个分类实际没有书，此处为防御性处理
-- ------------------------------------------------------------
UPDATE nov_novel
SET cate_id = 13,
    cate_name = '其他类型',
    updated_at = UNIX_TIMESTAMP()
WHERE deleted_at = 0
  AND cate_id IN (5, 8, 10, 12);

-- ------------------------------------------------------------
-- 3. 软删除这 4 个冷门分类
--    GetAll() 带 deleted_at=0 过滤，软删除后导航与后台列表都不再显示
-- ------------------------------------------------------------
UPDATE nov_cate
SET deleted_at = UNIX_TIMESTAMP(),
    updated_at = UNIX_TIMESTAMP()
WHERE id IN (5, 8, 10, 12)
  AND deleted_at = 0;

